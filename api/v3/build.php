<?php
declare(strict_types=1);

/**
 * Generator of API v3. Reads the SQL of the database (API_JAM/db_jam.sql) and writes, for every
 * table, the four files of its entity:
 *
 *   Models/Customer.php                table, key, columns and types
 *   Schemas/CustomerSchema.php         input rules with BaseSchema
 *   Controllers/CustomerController.php model + schema (access rules in JamController)
 *   Routers/CustomerRouter.php         addCrudRoutes('/customer', ...)
 *
 * Usage (from the api/v3 folder):   php build.php
 *
 * It only deletes and rewrites files that carry the GENERATED mark. Files written by hand (Auth,
 * Shop, Admin, Services, Core, CustomerController...) are left alone. The tables without CRUD
 * are listed at the end.
 */

const MARCA = '// GENERATED by build.php. Do not edit by hand: change the SQL or the rules and generate again.';

const FUENTE = __DIR__ . '/../../API_JAM/db_jam.sql';

/** Tables without generic CRUD: sessions, credentials, logs, or tables with their own routes. */
const SIN_API = [
    'customer_credential', 'customer_session', 'password_reset', 'audit_log', 'message_log',
    'verification_code', 'email_outbox', 'site_visit', 'search_log', 'app_install', 'mirror_sync',
    'order_status_history',
];

/** List order when it is not the primary key. */
const ORDEN = ['season_theme' => '[priority] DESC, [id_theme]'];

/**
 * Tables nobody writes through the API, not even the administrator. account_tier holds the
 * permissions of every account type (can_manage_store): if it could be edited, an administrator
 * could give the panel to every Estándar customer. It only changes with a SQL script.
 */
const SOLO_LECTURA = ['account_tier'];

/** Tables whose read (GET) is public: the store asks for them without a session. */
const LECTURA_PUBLICA = ['promotion', 'state', 'season_theme'];

/** Columns written by the server, never by the client. */
const CAMPOS_SERVIDOR = ['source_node', 'updated_at', 'deleted', 'created_at'];

/** Columns that never leave in a response. */
const OCULTAS = ['password_hash', 'source_node', 'deleted', 'row_version'];

const TIPOS = [
    'VARCHAR' => 'string', 'CHAR' => 'string', 'NVARCHAR' => 'string', 'NCHAR' => 'string',
    'INT' => 'integer', 'TINYINT' => 'integer', 'SMALLINT' => 'integer', 'BIGINT' => 'integer',
    'DECIMAL' => 'number', 'NUMERIC' => 'number', 'FLOAT' => 'number',
    'BIT' => 'boolean', 'DATE' => 'date', 'DATETIME' => 'datetime', 'DATETIME2' => 'datetime', 'TIME' => 'time',
];

/** SQL Server types the reader recognizes (the ones missing from TIPOS stop the generation). */
const TIPOS_SQL = [
    'VARCHAR', 'CHAR', 'NVARCHAR', 'NCHAR', 'INT', 'TINYINT', 'SMALLINT', 'BIGINT', 'DECIMAL', 'NUMERIC',
    'FLOAT', 'REAL', 'MONEY', 'BIT', 'DATE', 'DATETIME', 'DATETIME2', 'TIME', 'DATETIMEOFFSET', 'SMALLDATETIME',
    'VARBINARY', 'BINARY', 'UNIQUEIDENTIFIER', 'XML', 'TEXT', 'NTEXT', 'ROWVERSION',
];

function fail(string $message): never
{
    fwrite(STDERR, "ERROR: $message\n");
    exit(1);
}

function studly(string $snake): string
{
    return implode('', array_map('ucfirst', explode('_', $snake)));
}

/** @return array<string, mixed> */
function column(string $name, string $type, ?string $len, ?string $scale, string $rest): array
{
    $upper = strtoupper($type);
    $nullable = !preg_match('/NOT NULL/i', $rest);
    $identity = (bool) preg_match('/IDENTITY/i', $rest);
    $hasDefault = (bool) preg_match('/\bDEFAULT\b/i', $rest);
    $isMax = $len === null && (bool) preg_match('/^\s*\(\s*MAX\s*\)/i', $rest);
    return [
        'name' => $name,
        'kind' => TIPOS[$upper] ?? 'unknown',
        'type' => $upper,
        'len' => $len !== null ? (int) $len : null,
        'max_text' => $isMax,
        'scale' => $scale !== null ? (int) $scale : null,
        'nullable' => $nullable,
        'identity' => $identity,
        'required' => !$nullable && !$hasDefault && !$identity,
        'enum' => null,
        'min' => null,
        'max' => null,
    ];
}

/** Read the CHECK of a column: IN (...), BETWEEN, >= and >. */
function apply_checks(array &$columns, string $text): void
{
    preg_match_all('/CHECK \((\w+) IN \(([^)]*)\)\)/i', $text, $enums, PREG_SET_ORDER);
    foreach ($enums as $e) {
        if (isset($columns[$e[1]])) {
            preg_match_all("/'([^']*)'/", $e[2], $values);
            $columns[$e[1]]['enum'] = $values[1];
        }
    }
    preg_match_all('/CHECK \((\w+) BETWEEN (-?\d+) AND (-?\d+)\)/i', $text, $ranges, PREG_SET_ORDER);
    foreach ($ranges as $r) {
        if (isset($columns[$r[1]])) {
            $columns[$r[1]]['min'] = (int) $r[2];
            $columns[$r[1]]['max'] = (int) $r[3];
        }
    }
    preg_match_all('/CHECK \((\w+) >= (-?\d+)\)/i', $text, $mins, PREG_SET_ORDER);
    foreach ($mins as $m) {
        if (isset($columns[$m[1]]) && $columns[$m[1]]['min'] === null) {
            $columns[$m[1]]['min'] = (int) $m[2];
        }
    }
    preg_match_all('/CHECK \((\w+) > (-?\d+)\)/i', $text, $greater, PREG_SET_ORDER);
    foreach ($greater as $g) {
        if (isset($columns[$g[1]]) && $columns[$g[1]]['min'] === null) {
            $columns[$g[1]]['min'] = (int) $g[2] + 1;
        }
    }
}

/** Read CREATE TABLE and ALTER TABLE ... ADD of the script, in order. */
function load_tables(): array
{
    $sql = @file_get_contents(FUENTE);
    if ($sql === false) {
        fail('cannot read ' . FUENTE);
    }
    $sql = preg_replace('/^\s*--.*$/m', '', $sql);
    $tables = [];

    preg_match_all('/CREATE TABLE (?:dbo\.)?(\w+) \((.*?)\n\);/s', $sql, $creates, PREG_SET_ORDER);
    foreach ($creates as $c) {
        $columns = [];
        $pk = [];
        if (preg_match('/PRIMARY KEY \(([^)]*)\)/i', $c[2], $p)) {
            $pk = array_map('trim', explode(',', $p[1]));
        }
        foreach (explode("\n", $c[2]) as $line) {
            $line = trim(rtrim(trim($line), ','));
            if ($line === '' || preg_match('/^(CONSTRAINT|PRIMARY|UNIQUE|CHECK|FOREIGN|INDEX)\b/i', $line)) {
                continue;
            }
            // Only a column when the second token is a SQL type (a CHECK on several lines is not)
            if (preg_match('/^(\w+)\s+(\w+)(?:\((\d+)(?:,\s*(\d+))?\))?(.*)$/', $line, $col)
                && in_array(strtoupper($col[2]), TIPOS_SQL, true)) {
                $len = isset($col[3]) && $col[3] !== '' ? $col[3] : null;
                $scale = isset($col[4]) && $col[4] !== '' ? $col[4] : null;
                $columns[$col[1]] = column($col[1], $col[2], $len, $scale, $col[5]);
                if (preg_match('/PRIMARY KEY/i', $col[5])) {
                    $pk[] = $col[1];
                }
            }
        }
        apply_checks($columns, $c[2]);
        $tables[$c[1]] = ['columns' => $columns, 'pk' => array_values(array_unique($pk))];
    }

    preg_match_all('/ALTER TABLE (?:dbo\.)?(\w+)\s+ADD\s+(?!CONSTRAINT\b)(\w+)\s+(\w+)(?:\((\d+)(?:,\s*(\d+))?\))?([^;]*);/s', $sql, $alters, PREG_SET_ORDER);
    foreach ($alters as $a) {
        if (!isset($tables[$a[1]])) {
            fail("ALTER on an unknown table: {$a[1]}");
        }
        $len = isset($a[4]) && $a[4] !== '' ? $a[4] : null;
        $scale = isset($a[5]) && $a[5] !== '' ? $a[5] : null;
        $tables[$a[1]]['columns'][$a[2]] = column($a[2], $a[3], $len, $scale, $a[6]);
        apply_checks($tables[$a[1]]['columns'], $a[6]);
    }
    return $tables;
}

function lit(mixed $value): string
{
    return $value === null ? 'null' : (string) $value;
}

function quoted_list(array $items, string $indent): string
{
    if ($items === []) {
        return '';
    }
    return "\n" . implode(",\n", array_map(static fn ($i) => "$indent'$i'", $items)) . ",\n    ";
}

/** Schema line for a writable column. */
function schema_line(array $c): string
{
    $field = "'{$c['name']}'";
    $required = $c['required'] ? 'required: true, ' : '';
    if ($c['kind'] === 'string' && $c['enum'] !== null) {
        $options = '[' . implode(', ', array_map(static fn ($v) => "'$v'", $c['enum'])) . ']';
        $call = "BaseSchema::validateEnum(\$data, $field, $options, \$partial);";
        // When it is not required (NULL or DEFAULT), it is only checked when the body sends it
        return $c['required']
            ? $call
            : "if (array_key_exists($field, \$data) && \$data[$field] !== null) {\n            $call\n        }";
    }
    switch ($c['kind']) {
        case 'string':
            if ($c['max_text']) {
                return "BaseSchema::validateText(\$data, $field, {$required}partial: \$partial);";
            }
            return "BaseSchema::validateString(\$data, $field, " . lit($c['len']) . ", {$required}partial: \$partial);";
        case 'integer':
            $min = $c['min'] ?? match ($c['type']) {
                'TINYINT' => 0,
                default => null,
            };
            $max = $c['max'] ?? match ($c['type']) {
                'TINYINT' => 255,
                'SMALLINT' => 32767,
                'INT' => 2147483647,
                default => null,
            };
            $range = ($min !== null ? "minimum: $min, " : '') . ($max !== null ? "maximum: $max, " : '');
            return "BaseSchema::validateInteger(\$data, $field, {$range}{$required}partial: \$partial);";
        case 'number':
            $scale = $c['scale'] ?? 0;
            $max = $c['len'] !== null ? pow(10, $c['len'] - $scale) - pow(10, -$scale) : null;
            $fmt = static fn ($v) => sprintf('%.' . $scale . 'F', $v);
            $range = ($c['min'] !== null ? 'minimum: ' . $fmt($c['min']) . ', ' : '')
                . ($max !== null ? 'maximum: ' . $fmt($max) . ', ' : '');
            return "BaseSchema::validateNumber(\$data, $field, {$range}{$required}partial: \$partial);";
        case 'boolean':
            return "BaseSchema::validateBoolean(\$data, $field, {$required}partial: \$partial);";
        case 'date':
            return "BaseSchema::validateDate(\$data, $field, {$required}partial: \$partial);";
        case 'datetime':
            return "BaseSchema::validateDatetime(\$data, $field, {$required}partial: \$partial);";
        case 'time':
            return "BaseSchema::validateTime(\$data, $field, {$required}partial: \$partial);";
    }
    fail("type without validator: {$c['name']} ({$c['type']})");
}

function render_schema(string $class, string $table, array $writable, bool $hasPassword): string
{
    $lines = array_map(static fn ($c) => '        ' . schema_line($c), $writable);
    if ($hasPassword) {
        $lines[] = "        BaseSchema::validateString(\$data, 'password', 72, partial: \$partial);";
    }
    return "<?php\n" . MARCA . "\ndeclare(strict_types=1);\n\nnamespace Apicore\\Schemas;\n\n"
        . "/**\n * $class input schema: field rules of the `$table` table.\n *\n"
        . " * Layer: schemas (cross-cutting). Validation only: no HTTP, no SQL. The types,\n"
        . " * lengths and CHECK constraints come from API_JAM/db_jam.sql.\n */\n"
        . "final class {$class}Schema\n{\n"
        . "    /**\n     * Validate a $table payload. \$partial (PATCH) checks only the fields sent.\n     *\n"
        . "     * @param array<string, mixed> \$data\n     */\n"
        . "    public static function validate(array \$data, bool \$partial = false): void\n    {\n"
        . implode("\n", $lines) . "\n    }\n}\n";
}

function render_model(string $class, string $table, string $id, array $columns, array $writable, bool $hasPassword): string
{
    $writableNames = array_map(static fn ($c) => $c['name'], $writable);
    if ($hasPassword) {
        $writableNames[] = 'password_hash';
    }
    $hidden = array_values(array_filter(OCULTAS, static fn ($n) => isset($columns[$n])));
    $byKind = static fn (string $kind) => array_values(array_map(
        static fn ($c) => $c['name'],
        array_filter($columns, static fn ($c) => $c['kind'] === $kind && !in_array($c['name'], OCULTAS, true)),
    ));
    $identity = $columns[$id]['identity'];
    $lines = [
        "    protected const TABLE_NAME = '$table';",
        "    protected const ID_COLUMN = '$id';",
        '    protected const COLUMNS = [' . quoted_list($writableNames, '        ') . '];',
    ];
    if ($hidden !== []) {
        $lines[] = '    protected const HIDDEN_COLUMNS = [' . quoted_list($hidden, '        ') . '];';
    }
    if (!$identity) {
        $lines[] = '    protected const ID_IS_IDENTITY = false;';
    }
    if (isset($columns['deleted'])) {
        $lines[] = '    protected const SOFT_DELETE = true;';
    }
    if (isset($columns['updated_at'])) {
        $lines[] = '    protected const HAS_UPDATED_AT = true;';
    }
    if (isset($columns['source_node'])) {
        $lines[] = "    protected const SOURCE_NODE = 'php_api';";
    }
    if (isset(ORDEN[$table])) {
        $lines[] = "    protected const ORDER_BY = '" . ORDEN[$table] . "';";
    }
    foreach (['integer' => 'INTEGER_COLUMNS', 'boolean' => 'BOOLEAN_COLUMNS', 'number' => 'DECIMAL_COLUMNS'] as $kind => $const) {
        $names = $byKind($kind);
        if ($names !== []) {
            $lines[] = "    protected const $const = [" . quoted_list($names, '        ') . '];';
        }
    }
    return "<?php\n" . MARCA . "\ndeclare(strict_types=1);\n\nnamespace Apicore\\Models;\n\n"
        . "/**\n * $class model: only the table definition of `$table`.\n *\n"
        . " * Layer: models. No validation and no HTTP here.\n */\n"
        . "final class $class extends BaseModel\n{\n" . implode("\n", $lines) . "\n}\n";
}

function render_controller(string $class, string $table, bool $publicRead, bool $hasPassword): string
{
    $lines = [
        "    protected const MODEL_CLASS = $class::class;",
        "    protected const SCHEMA = {$class}Schema::class;",
    ];
    if ($publicRead) {
        $lines[] = '    protected const PUBLIC_READ = true;';
    }
    if (in_array($table, SOLO_LECTURA, true)) {
        $lines[] = '    protected const READ_ONLY = true;';
    }
    if ($hasPassword) {
        $lines[] = '    protected const HAS_PASSWORD = true;';
    }
    return "<?php\n" . MARCA . "\ndeclare(strict_types=1);\n\nnamespace Apicore\\Controllers;\n\n"
        . "use Apicore\\Models\\$class;\nuse Apicore\\Schemas\\{$class}Schema;\n\n"
        . "/**\n * $class controller: only the model and schema of the `$table` table.\n *\n"
        . " * Layer: controllers. The generic CRUD flow lives in BaseController and the\n"
        . " * store access rules in JamController.\n */\n"
        . "final class {$class}Controller extends JamController\n{\n" . implode("\n", $lines) . "\n}\n";
}

function render_router(string $class, string $table, bool $publicRead): string
{
    $label = ucfirst(str_replace('_', ' ', $table));
    $public = $publicRead ? ", publicMethods: ['GET']" : '';
    $note = $publicRead ? ' (GET public)' : ' (all protected)';
    return "<?php\n" . MARCA . "\ndeclare(strict_types=1);\n\nnamespace Apicore\\Routers;\n\n"
        . "use Apicore\\Controllers\\{$class}Controller;\nuse Apicore\\Core\\Router;\n\n"
        . "/**\n * $class routes: only wires the `/$table` URLs to {$class}Controller$note.\n *\n"
        . " * Layer: routers. One file per entity; RouterRegistry discovers them.\n */\n"
        . "final class {$class}Router\n{\n"
        . "    public static function register(Router \$router): void\n    {\n"
        . "        \$router->addCrudRoutes('/$table', {$class}Controller::class, '$label'$public);\n"
        . "    }\n}\n";
}

function clean(string $folder): void
{
    foreach (glob("$folder/*.php") ?: [] as $file) {
        $content = (string) file_get_contents($file);
        if (str_contains($content, MARCA)) {
            unlink($file);
        }
    }
}

/**
 * Write a generated file. A file already written by hand (without the mark) is kept: for example
 * CustomerController, which adds the rules about account types.
 */
function write_generated(string $path, string $content): void
{
    global $aMano;
    $current = is_file($path) ? (string) file_get_contents($path) : '';
    if ($current !== '' && !str_contains($current, MARCA)) {
        $aMano[] = basename(dirname($path)) . '/' . basename($path);
        return;
    }
    file_put_contents($path, $content);
}

// ---------------------------------------------------------------------------

$aMano = [];
$tables = load_tables();
foreach (['Schemas', 'Models', 'Controllers', 'Routers'] as $folder) {
    clean(__DIR__ . "/$folder");
}

$generadas = [];
$sinApi = [];
foreach ($tables as $name => $t) {
    if (in_array($name, SIN_API, true)) {
        $sinApi[] = "$name (internal or with its own routes)";
        continue;
    }
    $pk = $t['pk'];
    if (count($pk) !== 1 || !isset($t['columns'][$pk[0]]) || $t['columns'][$pk[0]]['kind'] !== 'integer') {
        $sinApi[] = "$name (composite or non numeric primary key)";
        continue;
    }

    $id = $pk[0];
    $columns = $t['columns'];
    $writable = [];
    foreach ($columns as $col => $c) {
        if (in_array($col, OCULTAS, true) || in_array($col, CAMPOS_SERVIDOR, true) || $c['type'] === 'ROWVERSION') {
            continue;
        }
        if ($col === $id && $c['identity']) {
            continue;
        }
        if ($c['kind'] === 'unknown') {
            fail("unknown type in $name.$col: {$c['type']}");
        }
        $writable[] = $c;
    }
    $hasPassword = isset($columns['password_hash']);
    $publicRead = in_array($name, LECTURA_PUBLICA, true);
    $class = studly($name);

    write_generated(__DIR__ . "/Schemas/{$class}Schema.php", render_schema($class, $name, $writable, $hasPassword));
    write_generated(__DIR__ . "/Models/$class.php", render_model($class, $name, $id, $columns, $writable, $hasPassword));
    write_generated(__DIR__ . "/Controllers/{$class}Controller.php", render_controller($class, $name, $publicRead, $hasPassword));
    write_generated(__DIR__ . "/Routers/{$class}Router.php", render_router($class, $name, $publicRead));
    $generadas[] = $name;
}

echo 'Tables with CRUD (' . count($generadas) . '): ' . implode(', ', $generadas) . "\n";
echo 'Without CRUD (' . count($sinApi) . "):\n  - " . implode("\n  - ", $sinApi) . "\n";
if ($aMano !== []) {
    echo 'Written by hand, left alone: ' . implode(', ', $aMano) . "\n";
}
